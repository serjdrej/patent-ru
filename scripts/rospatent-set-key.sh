#!/bin/bash
# Разово: сохраняет ROSPATENT_API_KEY в Keychain текущего пользователя macOS
# (через встроенную утилиту `security` — это тот же Keychain, что хранит
# пароли Safari/Mail, а не самодельное шифрование).
#
# Ключ хранится ВНЕ дерева скилла намеренно — сам скилл может быть установлен
# и переустановлен куда угодно (библиотека навыков, другая папка, другая копия
# репозитория), а ключ должен оставаться на месте независимо от этого.
# Настройка нужна один раз на компьютер, а не один раз на установку скилла.
#
# Что это даёт: ключ защищён тем же механизмом, что системные пароли —
# Keychain шифрует данные и привязывает доступ к вашей учётной записи macOS.
#
# Чего это НЕ даёт: любая программа, запущенная от вашего пользователя macOS,
# технически может запросить тот же элемент Keychain по имени службы; в
# части случаев macOS показывает системный запрос на подтверждение доступа
# при первом обращении из чужого процесса — это поведение самого Keychain,
# не наш контроль. Изоляция «только для этого скрипта» без выдачи явного
# ACL через Keychain Access — недостижима, как и на Windows с DPAPI.
#
# Запуск (в своём Terminal, не через агента — ключ вводится скрыто, как пароль):
#   ./rospatent-set-key.sh
#
# На Windows используйте вместо этого rospatent-set-key.ps1 (DPAPI).

set -euo pipefail

SERVICE="rospatent-api-key"
ACCOUNT="$USER"

read -r -s -p "Вставьте ключ ROSPATENT_API_KEY (ввод не отображается на экране): " KEY
echo

if [ -z "$KEY" ]; then
    echo "Пустой ввод — ключ не сохранён." >&2
    exit 1
fi

# -U обновляет существующую запись вместо ошибки "the specified item already exists"
security add-generic-password -a "$ACCOUNT" -s "$SERVICE" -w "$KEY" -U

echo "Сохранено в Keychain (служба: $SERVICE, аккаунт: $ACCOUNT)."
echo "Расположение не привязано к установке скилла — переустановка/перенос скилла ключ не затронет."
echo "Дальше используйте: ./rospatent.sh <команда>"
